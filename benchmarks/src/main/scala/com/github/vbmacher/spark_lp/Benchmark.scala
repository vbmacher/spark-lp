package com.github.vbmacher.spark_lp

import com.github.vbmacher.spark_lp.newton.{CgConfig, NewtonSolver}

import org.apache.spark.mllib.linalg.{DenseVector, Vector}
import org.apache.spark.rdd.RDD
import org.apache.spark.sql.SparkSession

/** Algorithm contract for performance benchmarks; CSV inventories define campaigns.
  * All implementations share solver settings, distributed generation, measurement
  * and independent validation. Keeping this contract in spark_lp permits direct
  * access to solver diagnostics without adapters or changes to the public LP API.
  */
trait Benchmark {
  def name: String
  def algorithm: NewtonSolver
  private[spark_lp] final def solve(costs: RDD[DenseVector], columns: RDD[Vector], rhs: DenseVector,
                  tolerance: Double, progress: SolveProgress => Unit,
                  inspect: (RDD[DenseVector], DenseVector, RDD[DenseVector]) => Unit)
                 (implicit spark: SparkSession): LP.SolveSummary =
    LP.solveSummary(costs, columns, rhs, tolerance = tolerance, maxIter = 100,
      solver = algorithm, cgTolerance = 1e-10, cgMaxIterations = 1000,
      cgConfig = CgConfig(1e-8, 1e-8, 0, 256L * 1024 * 1024),
      control = SolveControl(onProgress = progress), inspectConverged = Some(inspect))
}

/** Explicit algorithm registry used by the command-line runner. */
object Benchmark {
  val all: Seq[Benchmark] = Seq(CholeskyBenchmark, CGBenchmark)
  def named(name: String): Benchmark = all.find(_.name == name.toLowerCase).getOrElse(
    throw new IllegalArgumentException(s"Unknown benchmark '$name'; choose ${all.map(_.name).mkString(", ")}"))
}

/** Performance suite for the LP solver's direct Cholesky algorithm. Any campaign
  * case is generated by the shared DataFrame generator, then its original-LP
  * residuals and objective are independently checked. The runner records solve
  * time, outer iterations, termination and memory; CG-specific metrics are inapplicable.
  * Dense Gramian storage grows quadratically in m even for a sparse input matrix.
  * Select this instance with a scenario's "cholesky" backend.
  */
object CholeskyBenchmark extends Benchmark {
  override val name = "cholesky"
  override val algorithm: NewtonSolver = NewtonSolver.Cholesky
}

/** Performance suite for the LP solver's matrix-free conjugate-gradient algorithm.
  * Runs the same CSV-defined cases and independent validation as Cholesky, measuring
  * convergence, outer/inner iterations, restarts, preconditioner rank and solve time.
  * The shared trait pins CG tolerance, step limit and regularization; configuration
  * and actual rank are recorded so results from different settings stay separate.
  * Select this instance with a scenario's "cg" backend.
  */
object CGBenchmark extends Benchmark {
  override val name = "cg"
  override val algorithm: NewtonSolver = NewtonSolver.ConjugateGradient
}
